#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn client_packet_roundtrip() {
        let value = ClientPacketId::TradeCancel as i16;
        let decoded = ClientPacketId::try_from(value).expect("trade cancel id");
        assert_eq!(decoded, ClientPacketId::TradeCancel);

        let last_value = ClientPacketId::PurchaseGuildTerritory as i16;
        let decoded_last = ClientPacketId::try_from(last_value).expect("last id");
        assert_eq!(decoded_last, ClientPacketId::PurchaseGuildTerritory);
    }

    #[test]
    fn server_packet_roundtrip() {
        let value = ServerPacketId::ObjectMagic as i16;
        let decoded = ServerPacketId::try_from(value).expect("object magic id");
        assert_eq!(decoded, ServerPacketId::ObjectMagic);

        let last_value = ServerPacketId::GuildTerritoryPage as i16;
        let decoded_last = ServerPacketId::try_from(last_value).expect("last server id");
        assert_eq!(decoded_last, ServerPacketId::GuildTerritoryPage);
    }
}
